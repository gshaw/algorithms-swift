// The moon's rise, set and transit, how much is lit, its phase, and the dates of the next
// phases. One self-contained file: copy it into an app as it is.
//
// Held to https://algorithms.gshaw.ca/moon/ by https://github.com/gshaw/algorithms-swift.
// The moon is the main problem of ELP2000-82B (Chapront-Touzé and Chapront), from CDS
// catalogue VI/79, truncated to amplitudes of 0.5″ and 0.5 km; the sun is VSOP87D from
// CDS VI/81, truncated to 1e-7. Mean elements and the method follow Meeus, Astronomical
// Algorithms, chapters 22, 25, 40, 47 and 48. Events are found by searching the window.

import Foundation

public enum Moon {
    public enum Failure: Error, Equatable, Sendable {
        case outOfRange
        case invalidInput
    }

    public enum PhaseName: String, Sendable {
        case new, waxingCrescent, firstQuarter, waxingGibbous, full, waningGibbous, lastQuarter, waningCrescent
    }

    public struct Events: Equatable, Sendable {
        public var rise: Date?
        public var set: Date?
        public var transit: Date?
        public var isAlwaysUp: Bool
        public var isAlwaysDown: Bool
    }

    public struct Phase: Equatable, Sendable {
        /// 0 to 1, seen from the Earth's centre.
        public var illumination: Double
        /// The Sun–Moon–Earth angle: 0 at full, 180 at new.
        public var phaseAngle: Double
        public var name: PhaseName
    }

    public struct NextPhases: Equatable, Sendable {
        public var newMoon: Date
        public var firstQuarter: Date
        public var fullMoon: Date
        public var lastQuarter: Date
    }

    // MARK: - Phase

    /// How much is lit and the phase's name. The name comes from the elongation, in eight
    /// 45° bands each centred on its phase.
    public static func phase(at date: Date) -> Phase {
        let jd = julianDay(date)
        let m = moon(jd), s = sun(jd)
        let psi = acos(cos(radians(m.latitude)) * cos(radians(m.longitude - s.longitude)))
        let r = s.distance * 149_597_870.7
        let i = atan2(r * sin(psi), m.distance - r * cos(psi))
        let elongation = wrapped(m.longitude - s.longitude)
        let names: [PhaseName] = [.new, .waxingCrescent, .firstQuarter, .waxingGibbous, .full, .waningGibbous, .lastQuarter, .waningCrescent]
        return Phase(illumination: (1 + cos(i)) / 2, phaseAngle: degrees(i),
                     name: names[Int(wrapped(elongation + 22.5) / 45) % 8])
    }

    /// The first of each main phase from `start`.
    public static func nextPhases(after start: Date) -> NextPhases {
        let jd0 = julianDay(start)
        func elongation(_ jd: Double) -> Double { wrapped(moon(jd).longitude - sun(jd).longitude) }
        func next(_ target: Double) -> Date {
            func f(_ jd: Double) -> Double {
                let e = elongation(jd) - target
                return e > 180 ? e - 360 : e <= -180 ? e + 360 : e
            }
            var t = jd0, a = f(t)
            while true {
                let b = f(t + 0.25)
                if a < 0 && b >= 0 {
                    var lo = t, hi = t + 0.25
                    for _ in 0..<40 {
                        let mid = (lo + hi) / 2
                        if f(mid) >= 0 { hi = mid } else { lo = mid }
                    }
                    return date(julianDay: (lo + hi) / 2)
                }
                t += 0.25
                a = b
            }
        }
        return NextPhases(newMoon: next(0), firstQuarter: next(90), fullMoon: next(180), lastQuarter: next(270))
    }

    // MARK: - Rise, set and transit

    /// The first rise, set and transit in the window from `start` for `hours`, more than 0
    /// and at most 48, seen from the place: the top edge at the horizon, with 34′ of refraction.
    public static func events(latitude: Double, longitude: Double, start: Date, hours: Double = 24) throws(Failure) -> Events {
        guard (-90...90).contains(latitude), (-180...180).contains(longitude), hours > 0, hours <= 48 else { throw .outOfRange }
        let jd0 = julianDay(start), jd1 = jd0 + hours / 24
        let step = 5.0 / 1440

        func first(_ f: (Double) -> Double, rising: Bool) -> Date? {
            var t = jd0, a = f(t)
            while t < jd1 {
                let next = min(t + step, jd1), b = f(next)
                if rising ? (a < 0 && b >= 0) : (a >= 0 && b < 0) {
                    var lo = t, hi = next
                    for _ in 0..<30 {
                        let mid = (lo + hi) / 2
                        if (f(mid) >= 0) == rising { hi = mid } else { lo = mid }
                    }
                    let found = (lo + hi) / 2
                    return found < jd1 ? date(julianDay: found) : nil
                }
                t = next
                a = b
            }
            return nil
        }

        func aboveHorizon(_ jd: Double) -> Double {
            let p = topocentric(latitude: latitude, longitude: longitude, julianDay: jd)
            return p.altitude + 34.0 / 60 + p.semidiameter
        }
        var e = Events(isAlwaysUp: false, isAlwaysDown: false)
        e.rise = first(aboveHorizon, rising: true)
        e.set = first(aboveHorizon, rising: false)
        e.transit = first({ jd in
            let h = topocentric(latitude: latitude, longitude: longitude, julianDay: jd).hourAngle
            return h > 180 ? h - 360 : h
        }, rising: true)
        if e.rise == nil && e.set == nil {
            let up = aboveHorizon(jd0) > 0
            e.isAlwaysUp = up
            e.isAlwaysDown = !up
        }
        return e
    }

    // MARK: - Positions

    /// The moon's apparent ecliptic longitude and latitude (degrees) and distance (km).
    private static func moon(_ jd: Double) -> (longitude: Double, latitude: Double, distance: Double) {
        let t = (jd + 69.0 / 86400 - 2451545) / 36525
        let t2 = t * t, t3 = t2 * t, t4 = t3 * t
        let lp = 218.3164477 + 481267.88123421 * t - 0.0015786 * t2 + t3 / 538841 - t4 / 65194000
        let d = radians(297.8501921 + 445267.1114034 * t - 0.0018819 * t2 + t3 / 545868 - t4 / 113065000)
        let m = radians(357.5291092 + 35999.0502909 * t - 0.0001536 * t2 + t3 / 24490000)
        let mp = radians(134.9633964 + 477198.8675055 * t + 0.0087414 * t2 + t3 / 69699 - t4 / 14712000)
        let f = radians(93.2720950 + 483202.0175233 * t - 0.0036539 * t2 - t3 / 3526000 + t4 / 863310000)
        func argument(_ term: (Int, Int, Int, Int, Double)) -> Double {
            Double(term.0) * d + Double(term.1) * m + Double(term.2) * mp + Double(term.3) * f
        }
        let longitude = lp + elpLongitude.reduce(0) { $0 + $1.4 * sin(argument($1)) } / 3600
        let latitude = elpLatitude.reduce(0) { $0 + $1.4 * sin(argument($1)) } / 3600
        let distance = elpDistance.reduce(0) { $0 + $1.4 * cos(argument($1)) }
        return (wrapped(longitude + nutation(t).longitude), latitude, distance)
    }

    /// The sun's apparent ecliptic longitude (degrees) and distance (AU), Meeus 25 on VSOP87D.
    private static func sun(_ jd: Double) -> (longitude: Double, distance: Double) {
        let t = (jd + 69.0 / 86400 - 2451545) / 36525, tau = t / 10
        func sum(_ series: [[(Double, Double, Double)]]) -> Double {
            var total = 0.0, power = 1.0
            for terms in series {
                total += power * terms.reduce(0) { $0 + $1.0 * cos($1.1 + $1.2 * tau) }
                power *= tau
            }
            return total
        }
        let r = sum(vsopR)
        let longitude = degrees(sum(vsopL)) + 180 - 0.09033 / 3600 + nutation(t).longitude - 20.4898 / 3600 / r
        return (wrapped(longitude), r)
    }

    /// The main terms of nutation, in degrees (Meeus 22).
    private static func nutation(_ t: Double) -> (longitude: Double, obliquity: Double) {
        let omega = radians(125.04452 - 1934.136261 * t)
        let l = radians(280.4665 + 36000.7698 * t), lp = radians(218.3165 + 481267.8813 * t)
        return ((-17.20 * sin(omega) - 1.32 * sin(2 * l) - 0.23 * sin(2 * lp) + 0.21 * sin(2 * omega)) / 3600,
                (9.20 * cos(omega) + 0.57 * cos(2 * l) + 0.10 * cos(2 * lp) - 0.09 * cos(2 * omega)) / 3600)
    }

    /// The moon seen from a place on WGS84: geometric altitude of its centre, hour angle
    /// (degrees west, 0 to 360) and semidiameter (degrees).
    private static func topocentric(latitude: Double, longitude: Double, julianDay jd: Double)
        -> (altitude: Double, hourAngle: Double, semidiameter: Double) {
        let t = (jd + 69.0 / 86400 - 2451545) / 36525
        let m = moon(jd), n = nutation(t)
        let epsilon = radians(23.43929111 - (46.8150 * t + 0.00059 * t * t - 0.001813 * t * t * t) / 3600 + n.obliquity)
        let l = radians(m.longitude), b = radians(m.latitude)
        let ra = atan2(sin(l) * cos(epsilon) - tan(b) * sin(epsilon), cos(l))
        let dec = asin(sin(b) * cos(epsilon) + cos(b) * sin(epsilon) * sin(l))

        let tu = (jd - 2451545) / 36525
        let gmst = 280.46061837 + 360.98564736629 * (jd - 2451545) + 0.000387933 * tu * tu - tu * tu * tu / 38710000
        let theta = radians(gmst + n.longitude * cos(epsilon) + longitude)

        // The observer's place in the equatorial frame, on WGS84 (Meeus 11).
        let a = 6378.137, f = 1 / 298.257223563, phi = radians(latitude)
        let u = atan((1 - f) * tan(phi))
        let rhoSin = (1 - f) * sin(u), rhoCos = cos(u)
        let x = m.distance * cos(dec) * cos(ra) - a * rhoCos * cos(theta)
        let y = m.distance * cos(dec) * sin(ra) - a * rhoCos * sin(theta)
        let z = m.distance * sin(dec) - a * rhoSin
        let distance = (x * x + y * y + z * z).squareRoot()
        let raTopo = atan2(y, x), decTopo = asin(z / distance)

        let h = theta - raTopo
        let ex = -cos(h) * cos(decTopo) * sin(phi) + sin(decTopo) * cos(phi)
        let ey = -sin(h) * cos(decTopo)
        let ez = cos(h) * cos(decTopo) * cos(phi) + sin(decTopo) * sin(phi)
        return (degrees(atan2(ez, (ex * ex + ey * ey).squareRoot())), wrapped(degrees(h)), degrees(asin(1737.4 / distance)))
    }

    // MARK: - Helpers

    private static func julianDay(_ date: Date) -> Double { date.timeIntervalSince1970 / 86400 + 2440587.5 }
    private static func date(julianDay jd: Double) -> Date { Date(timeIntervalSince1970: (jd - 2440587.5) * 86400) }
    private static func radians(_ degrees: Double) -> Double { degrees * .pi / 180 }
    private static func degrees(_ radians: Double) -> Double { radians * 180 / .pi }

    private static func wrapped(_ degrees: Double) -> Double {
        let r = degrees.truncatingRemainder(dividingBy: 360)
        return r < 0 ? r + 360 : r
    }

